package org.armedbear.j.mode.markdown;

import static org.junit.jupiter.api.Assertions.assertEquals;

import org.armedbear.j.EditorHarness;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;

/**
 * The Markdown electric-pairs override: the fence, the emphasis
 * delimiter runs, and the link trigger. Each transition reads the
 * buffer at the keystroke, so the live keystroke and the vim {@code .}
 * replay of the same keys reach the same result. The closer is
 * generated by the first content character after an unmatched opener
 * run, never by the run itself, and a run that already closed an
 * earlier opener is not treated as a new opener.
 */
public class MarkdownElectricPairsTest {
    private EditorHarness h;

    @AfterEach
    public void tearDown() {
        if (h != null)
            h.close();
    }

    private EditorHarness md(String text) {
        h = EditorHarness.create(text).mode(MarkdownMode.getMode()).vim();
        return h;
    }

    private int caret() {
        return h.editor().getDotOffset();
    }

    // ------------------------------------------------ closer generation

    @Test
    public void firstContentCharAfterStrongOpenerGeneratesTheCloser() {
        md("\n");
        h.cursor(0, 0).keys("i**b");
        // The closer is generated by the `b`, not typed by the user.
        h.assertText("**b**\n");
        assertEquals(3, caret());
    }

    @Test
    public void firstContentCharAfterEmphasisOpenerGeneratesTheCloser() {
        md("\n");
        h.cursor(0, 0).keys("i*b");
        h.assertText("*b*\n");
        assertEquals(2, caret());
    }

    @Test
    public void noCloserGeneratedOnSpaceAfterOpener() {
        md("\n");
        h.cursor(0, 0).keys("i** ");
        // A space is not content: `** ` is not emphasis.
        h.assertText("** \n");
        assertEquals(3, caret());
    }

    // ---------------------------------------------------- closer role

    @Test
    public void secondStarClosesAndContentAfterItDoesNotReopen() {
        md("\n");
        h.cursor(0, 0).keys("i*b*");
        // The second `*` closed the emphasis; the caret sits after it.
        h.assertText("*b*\n");
        assertEquals(3, caret());
        h.keys("c");
        // The closing `*` is matched, so `c` is plain: no new closer.
        h.assertText("*b*c\n");
        assertEquals(4, caret());
    }

    @Test
    public void punctuationBeforeAMatchedCloserDoesNotMakeItANewOpener() {
        md("\n");
        // `*b!*` ends in a matched closer whose preceding char is
        // punctuation; a predecessor-only predicate would wrongly call
        // it an opener and add a star.
        h.cursor(0, 0).keys("i*b!*c");
        h.assertText("*b!*c\n");
        assertEquals(5, caret());
    }

    @Test
    public void fullStrongTypingStillWorks() {
        md("\n");
        h.cursor(0, 0).keys("i**bold**");
        h.assertText("**bold**\n");
        assertEquals(8, caret());
    }

    // ------------------------------------------- single-char closer skip

    @Test
    public void typingStarBeforeACloserRunSkipsOneDelimiterPerKeystroke() {
        md("**bold**\n");
        // Caret between `bold` and the closing `**`.
        h.cursor(0, 6).keys("i*");
        // One `*` skipped, not the whole run.
        h.assertText("**bold**\n");
        assertEquals(7, caret());
        h.keys("*");
        h.assertText("**bold**\n");
        assertEquals(8, caret());
    }

    // ------------------------------------------------------ run replay

    @Test
    public void closerGenerationReplaysIdentically() {
        md("\n\n");
        h.cursor(0, 0).keys("i**b<Esc>");
        h.assertText("**b**\n\n");
        // Replay on the next line: each replayed keystroke sees the
        // same starting context, so the closer is generated again.
        h.cursor(1, 0).keys(".<Esc>");
        h.assertText("**b**\n**b**\n");
    }

    // --------------------------------------------------------- fence

    @Test
    public void thirdBacktickAtLineStartOpensAFenceWithACloserBelow() {
        md("\n");
        h.cursor(0, 0).keys("i```");
        // The closing fence is on the line below; the caret stays after
        // the opening fence for the language name.
        h.assertText("```\n```\n");
        assertEquals(3, caret());
    }

    @Test
    public void singleBacktickPairsInline() {
        md("\n");
        h.cursor(0, 0).keys("i`");
        h.assertText("``\n");
        assertEquals(1, caret());
    }

    // --------------------------------------------------------- link

    @Test
    public void openParenAfterLinkTextPairsToEmptyParens() {
        md("\n");
        h.cursor(0, 0).keys("i[link](");
        // The `(` pairs to `()`, giving the link destination.
        h.assertText("[link]()\n");
        assertEquals(7, caret());
    }

    // --------------------------------------------------- escapes

    @Test
    public void escapedMarkerIsLiteralAndGeneratesNoCloser() {
        md("\\*\n");
        // The `*` is escaped, so typing content after it is plain.
        h.cursor(0, 2).keys("ib");
        h.assertText("\\*b\n");
        assertEquals(3, caret());
    }

    @Test
    public void markerInsideInlineCodeIsLiteral() {
        md("`*x`\n");
        // Inside a code span, nothing pairs.
        h.cursor(0, 3).keys("iy");
        h.assertText("`*xy`\n");
        assertEquals(4, caret());
    }

    // ------------------------------------------------ list markers

    @Test
    public void listMarkerStarIsNotAnEmphasisOpener() {
        md("* item\n");
        // The `* ` is a bullet, not emphasis: content after it is plain.
        h.cursor(0, 2).keys("ib");
        h.assertText("* bitem\n");
        assertEquals(3, caret());
    }

    // ------------------------------------------- underscore / tilde

    @Test
    public void underscoreEmphasisGeneratesItsCloser() {
        md("\n");
        h.cursor(0, 0).keys("i_x");
        h.assertText("_x_\n");
        assertEquals(2, caret());
    }

    @Test
    public void tildeStrikethroughGeneratesItsCloser() {
        md("\n");
        h.cursor(0, 0).keys("i~~x");
        h.assertText("~~x~~\n");
        assertEquals(3, caret());
    }
}
